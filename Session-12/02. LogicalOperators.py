
a = True
b = False
print ("a and b:",a and b)  # Logical AND   (Both True for True)
print ("a or b:",a or b)    # Logical OR    (At least one True for True)
print ("not a:",not a)      # Logical NOT   (negates the value, True becomes False and vice versa)
print ("not b:",not b)      # Logical NOT   (negates the value, True becomes False and vice versa)