a = 5
b = 2

print ("Addition(a+b):",a+b)        # Addition
print ("Subtraction(a-b):",a-b)     # Subtraction
print ("Multiplication (a*b):",a*b) # Multiplication
print ("Division (a/b):",a/b)       # Division
print ("Modulus (a%b):",a%b)        # Modulus (Remainder)
print ("Exponential (a**b):",a**b)  # Exponentiation (a raised to the power of b)
print ("Floor Division (a//b):",a//b) # Floor Division (Quotient without the remainder)